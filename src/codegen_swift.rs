fn is_void(ret: &str) -> bool {
    matches!(ret.trim(), "Void" | "()" | "Swift.Void")
}

/// `name(a0, to: a1)`: the call with the original argument labels.
fn call(sig: &SwiftSig, args: &[String]) -> String {
    let parts: Vec<String> = sig
        .params
        .iter()
        .zip(args)
        .map(|(p, a)| match &p.label {
            Some(l) => format!("{l}: {a}"),
            None => a.clone(),
        })
        .collect();
    format!("{}({})", sig.name, parts.join(", "))
}

fn signatures(m: &Manifest) -> Vec<(&crate::ts::exports::ExportedFn, SwiftSig)> {
    m.exports
        .iter()
        .filter_map(|f| {
            let proto = f.prototype.as_deref()?;
            Some((f, signature(proto)?))
        })
        .collect()
}

pub fn wrapper(m: &Manifest) -> String {
    let native = native_module(m);
    let error = error_type(m);
    let mut out = format!(
        "// The Rust port of `{unit}`, generated by rust-anything: the same functions, with the same\n\
         // labels, defaults and `throws`, each calling the Rust library through the C module\n\
         // `{native}` (in `swift/{native}/`). Compile it into the target in place of the original\n\
         // file. Regenerate with `rust-anything refresh`.\n\n\
         import {native}\n\n\
         /// An error a Rust port returned: `Err(\"Type: message\")` arrives as `typeName` and\n\
         /// `message`.\n\
         public struct {error}: Error, CustomStringConvertible {{\n    \
         public let typeName: String\n    \
         public let message: String\n    \
         public var description: String {{ message }}\n}}\n\n\
         {codec}\n\
         fileprivate func raCall(_ name: String, _ args: [RAJSON]) -> Result<RAJSON, {error}> {{\n    \
         guard let ptr = rust_anything_call(name, raText(.array(args))) else {{\n        \
         fatalError(\"rust-anything: no answer from `\\(name)`\")\n    }}\n    \
         let text = String(cString: ptr)\n    \
         rust_anything_free(ptr)\n    \
         var parser = RAParser(text)\n    \
         guard let answer = try? parser.parse(), case .object(let pairs) = answer, let first = pairs.first else {{\n        \
         fatalError(\"rust-anything: unreadable answer from `\\(name)`: \\(text)\")\n    }}\n    \
         switch (first.0, first.1) {{\n    \
         case (\"ok\", let value):\n        return .success(value)\n    \
         case (\"error\", .string(let message)):\n        \
         if let colon = message.range(of: \": \") {{\n            \
         return .failure({error}(typeName: String(message[..<colon.lowerBound]), message: String(message[colon.upperBound...])))\n        }}\n        \
         return .failure({error}(typeName: \"\", message: message))\n    \
         case (\"panic\", .string(let message)):\n        \
         fatalError(\"Rust panic: \\(message)\")\n    \
         default:\n        \
         fatalError(\"rust-anything: unreadable answer from `\\(name)`: \\(text)\")\n    }}\n}}\n\n\
         fileprivate func raTrap<T>(_ body: () throws -> T) -> T {{\n    \
         do {{ return try body() }} catch {{ fatalError(\"rust-anything: \\(error)\") }}\n}}\n",
        unit = m.unit,
        codec = codec(),
    );
    for (f, sig) in signatures(m) {
        let args: Vec<String> = sig
            .params
            .iter()
            .map(|p| format!("{}.raJSON", p.name))
            .collect();
        let invoke = format!("raCall(\"{}\", [{}])", f.name, args.join(", "));
        let void = is_void(&sig.ret);
        let body = match (sig.throws, void) {
            (true, true) => format!("    _ = try {invoke}.get()"),
            (true, false) => format!(
                "    let answer = try {invoke}.get()\n    return raTrap {{ try raDecode(answer) }}"
            ),
            (false, true) => format!("    _ = raTrap {{ try {invoke}.get() }}"),
            (false, false) => format!("    return raTrap {{ try raDecode({invoke}.get()) }}"),
        };
        let proto = f.prototype.as_deref().unwrap_or_default();
        let _ = write!(out, "\n{proto} {{\n{body}\n}}\n");
    }
    out
}

/// `main.swift` of the driver: reads a JSON array of cases, runs each, and writes one JSON line
/// per case (`{"i": n, "ok": v}`, `{"i": n, "error": ..., "error_type": ...}`, or
/// `{"i": n, "skip": true}` for arguments that do not convert). `rust` is the build with the
/// wrapper, whose errors carry the port's type name.
pub fn driver(m: &Manifest, rust: bool) -> String {
    let mut arms = String::new();
    for (f, sig) in signatures(m) {
        let names: Vec<String> = (0..sig.params.len()).map(|i| format!("p{i}")).collect();
        let _ = writeln!(
            arms,
            "    case {}:",
            serde_json::Value::from(f.name.clone())
        );
        if !names.is_empty() {
            let decls: Vec<String> = sig
                .params
                .iter()
                .zip(&names)
                .map(|(p, n)| format!("{n}: {}", p.ty))
                .collect();
            let _ = writeln!(arms, "        let {}", decls.join(", "));
            let assigns: Vec<String> = names
                .iter()
                .enumerate()
                .map(|(i, n)| format!("{n} = try raDecode(raArg(a, {i}))"))
                .collect();
            let _ = writeln!(
                arms,
                "        do {{ {} }} catch {{ return .badInput }}",
                assigns.join("; ")
            );
        }
        let invoke = call(&sig, &names);
        let line = match (sig.throws, is_void(&sig.ret)) {
            (true, true) => {
                format!(
                    "do {{ try {invoke}; return .ok(.null) }} catch {{ return .thrown(error) }}"
                )
            }
            (true, false) => {
                format!(
                    "do {{ return .ok(try {invoke}.raJSON) }} catch {{ return .thrown(error) }}"
                )
            }
            (false, true) => format!("{invoke}; return .ok(.null)"),
            (false, false) => format!("return .ok({invoke}.raJSON)"),
        };
        let _ = writeln!(arms, "        {line}");
    }
    let rust_error = if rust {
        format!(
            "    if let e = e as? {} {{ return (e.message, e.typeName) }}\n",
            error_type(m)
        )
    } else {
        String::new()
    };
    format!(
        "// The rust-anything driver for `{unit}`, generated: runs recorded cases.\n\n\
         import Foundation\n\n\
         {codec}\n\
         fileprivate enum RAOutcome {{\n    case ok(RAJSON)\n    case thrown(Error)\n    case badInput\n}}\n\n\
         fileprivate func raArg(_ a: [RAJSON], _ i: Int) -> RAJSON {{\n    \
         guard i < a.count else {{ return .null }}\n    \
         if case .object(let pairs) = a[i], pairs.count == 1, pairs[0].0 == \"$undefined\" {{ return .null }}\n    \
         return a[i]\n}}\n\n\
         fileprivate func raErrorFields(_ e: Error) -> (String, String) {{\n\
         {rust_error}    \
         var type = String(reflecting: Swift.type(of: e))\n    \
         if type.hasPrefix(\"{DRIVER_MODULE}.\") {{ type.removeFirst(\"{DRIVER_MODULE}.\".count) }}\n    \
         return (String(describing: e), type)\n}}\n\n\
         fileprivate func raCase(_ name: String, _ a: [RAJSON]) -> RAOutcome {{\n    \
         switch name {{\n{arms}    default:\n        return .badInput\n    }}\n}}\n\n\
         fileprivate func raAppend(_ path: String, _ text: String) {{\n    \
         guard let handle = FileHandle(forWritingAtPath: path) else {{ return }}\n    \
         handle.seekToEndOfFile()\n    \
         handle.write(text.data(using: .utf8)!)\n    \
         handle.closeFile()\n}}\n\n\
         fileprivate func raMain() throws {{\n    \
         let argv = CommandLine.arguments\n    \
         let input = String(decoding: FileManager.default.contents(atPath: argv[1]) ?? Data(), as: UTF8.self)\n    \
         var parser = RAParser(input)\n    \
         guard case .array(let cases) = try parser.parse() else {{ throw RAJSONError(\"the cases are not a JSON array\") }}\n    \
         FileManager.default.createFile(atPath: argv[2], contents: nil)\n    \
         let progress = ProcessInfo.processInfo.environment[\"RUST_ANYTHING_PROGRESS\"]\n    \
         for (index, c) in cases.enumerated() {{\n        \
         if let p = progress {{ raAppend(p, \"\\(index)\\n\") }}\n        \
         guard case .object(let fields) = c else {{ continue }}\n        \
         var name = \"\"\n        \
         var args: [RAJSON] = []\n        \
         for (k, v) in fields {{\n            \
         if k == \"fn\", case .string(let s) = v {{ name = s }}\n            \
         if k == \"args\", case .array(let xs) = v {{ args = xs }}\n        }}\n        \
         var line: [(String, RAJSON)] = [(\"i\", .int(index))]\n        \
         switch raCase(name, args) {{\n        \
         case .ok(let v): line.append((\"ok\", v))\n        \
         case .thrown(let e):\n            \
         let (message, type) = raErrorFields(e)\n            \
         line.append((\"error\", .string(message)))\n            \
         line.append((\"error_type\", .string(type)))\n        \
         case .badInput: line.append((\"skip\", .bool(true)))\n        }}\n        \
         raAppend(argv[2], raText(.object(line)) + \"\\n\")\n    }}\n}}\n\n\
         try raMain()\n",
        unit = m.unit,
        codec = codec(),
    )
}

